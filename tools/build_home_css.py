"""合併工作坊首頁 CSS，保留層疊順序；來源仍在各原始樣式表。"""
from pathlib import Path

ASSETS = Path(__file__).resolve().parents[1] / 'site/assets'
SOURCES = ['site.css', 'responsive.css', 'studio.css', 'home-art-direction.css',
           'brand/brand-tokens.css', 'hub.css']


def build():
    parts = ['/* Generated by tools/build_home_css.py; edit source stylesheets. */\n']
    for name in SOURCES:
        css = (ASSETS / name).read_text(encoding='utf-8')
        assert '@import' not in css and '@charset' not in css, name
        # brand tokens 只有變數，沒有相對資源；其他來源與輸出同在 assets/。
        if name.startswith('brand/'):
            assert 'url(' not in css, 'Rebase brand resource URLs before bundling'
        parts.append('\n/* ' + name + ' */\n' + css.rstrip() + '\n')
    text = ''.join(parts)
    output = ASSETS / 'home-bundle.css'
    if not output.exists() or output.read_text(encoding='utf-8') != text:
        output.write_text(text, encoding='utf-8', newline='\n')
        print('built home-bundle.css', len(text.encode('utf-8')), 'bytes')


if __name__ == '__main__':
    build()
